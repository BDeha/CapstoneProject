CREATE DATABASE privilege_walk;
USE privilege_walk;

-- Stores the questions used in the walk
CREATE TABLE prompts (
    id INT AUTO_INCREMENT PRIMARY KEY,
    question TEXT NOT NULL,
    type ENUM('advantage', 'disadvantage') NOT NULL
);

-- Stores anonymized student progress
CREATE TABLE responses (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_alias VARCHAR(50), -- Generated by Identity Factory
    total_score INT DEFAULT 0
);